// Decision 219: the router hands the user's request to each worker when it starts, read from the lead's transcript.
// The text goes into the hook's answer only: not into the ledger, the daemon's files or the office and tab payloads.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { AWAITING_USER_MARKER } from '../src/continuation.ts';
import { PROMPT_TAIL_BYTES, readUserPrompts } from '../src/transcript.ts';
import { TOKEN, call as sealedApi, makeRepo, postHook, rmrf, rows, startTestDaemon, tmpDir, type HookInput, type TestDaemon } from './helpers.ts';

const MARKER = 'quartz-heron-5521';
const L2_PROMPT = `Refactor the validation module across multiple files and add an audit log (${MARKER}).`;
type Out = { hookSpecificOutput?: { additionalContext?: string; permissionDecision?: string; permissionDecisionReason?: string } };

// ------------------------------------------------------------------ the transcript

const user = (content: unknown, extra: Record<string, unknown> = {}) => JSON.stringify({ type: 'user', message: { role: 'user', content }, isSidechain: false, ...extra });
const assistant = (text: string) => JSON.stringify({ type: 'assistant', message: { role: 'assistant', model: 'claude-sonnet-5-5', content: [{ type: 'text', text }] } });

function transcriptFile(lines: string[]): { dir: string; file: string } {
  const dir = tmpDir('dic-handover-');
  const file = path.join(dir, 'main.jsonl');
  fs.writeFileSync(file, lines.join('\n') + '\n');
  return { dir, file };
}

test('decision 219: readUserPrompts takes the prompts the user typed, oldest first, and nothing else', () => {
  const { dir, file } = transcriptFile([
    user('an older request'),
    assistant('done'),
    user('the request'),
    user([{ type: 'tool_result', tool_use_id: 't1', content: 'file contents' }]),
    user('<task-notification>\n<task-id>a1</task-id>\n</task-notification>'),
    user('<command-name>/office</command-name>\n<command-message>office</command-message>'),
    user('<local-command-stdout>opened</local-command-stdout>'),
    user('Caveat: the messages below were generated by the user while running local commands.', { isMeta: true }),
    user('a worker\'s own prompt', { isSidechain: true }),
    user('/router level L2'),
    assistant(`Which one? ${AWAITING_USER_MARKER}`),
    user([{ type: 'text', text: 'the second one,' }, { type: 'image', source: {} }, { type: 'text', text: 'please' }]),
    '{"type":"user","message":{"content":"a line cut',
  ]);
  try {
    assert.deepEqual(readUserPrompts(file, 1), ['the second one,\nplease']);
    assert.deepEqual(readUserPrompts(file, 2), ['the request', 'the second one,\nplease']);
    assert.deepEqual(readUserPrompts(file, 3), ['an older request', 'the request', 'the second one,\nplease']);
    assert.equal(readUserPrompts(file, 4), undefined, 'fewer prompts than asked for: none, never a part');
    assert.equal(readUserPrompts(file, 0), undefined);
    assert.equal(readUserPrompts(path.join(dir, 'missing.jsonl'), 1), undefined);
    assert.equal(readUserPrompts('main.jsonl', 1), undefined, 'a relative path is not read');
    assert.equal(readUserPrompts(path.join(dir, 'main.txt'), 1), undefined);
  } finally { rmrf(dir); }
});

test('decision 219: a prompt further back than the read window is not taken half-read', () => {
  const big = 'x'.repeat(PROMPT_TAIL_BYTES);
  const { dir, file } = transcriptFile([user('the request'), user([{ type: 'tool_result', tool_use_id: 't', content: big }]), user('the answer')]);
  try {
    assert.deepEqual(readUserPrompts(file, 1), ['the answer']);
    assert.equal(readUserPrompts(file, 2), undefined);
  } finally { rmrf(dir); }
});

// ------------------------------------------------------------------ the router

let seq = 0;

/** A lead session whose transcript the test writes as Claude Code would: each typed prompt also lands in the file. */
function session(d: TestDaemon, sid: string, cwd: string, transcript: string, writeTranscript = true) {
  const post = async (h: HookInput): Promise<Out> => {
    const r = await postHook(d.port, { session_id: sid, cwd, transcript_path: transcript, ...h });
    assert.equal(r.status, 200, r.text);
    return r.body as Out;
  };
  const say = async (prompt: string): Promise<void> => {
    if (writeTranscript) fs.appendFileSync(transcript, user(prompt) + '\n');
    await post({ hook_event_name: 'UserPromptSubmit', prompt });
  };
  const call = (tag: string, role = 'coder', model = 'haiku', effort = 'low'): HookInput => ({
    hook_event_name: 'PreToolUse', tool_name: 'Agent', tool_use_id: `toolu_h${++seq}`,
    tool_input: { subagent_type: `do-it-all-claude-code:${role}`, prompt: `[subtask:${tag}]\n[scope: src/${tag.toLowerCase()}/**]\nwork`, model, effort },
  });
  const start = async (agent: string, role = 'coder'): Promise<string> =>
    (await post({ hook_event_name: 'SubagentStart', agent_id: agent, agent_type: `do-it-all-claude-code:${role}` })).hookSpecificOutput?.additionalContext ?? '';
  return { post, say, call, start };
}

async function withDaemon(fn: (d: TestDaemon, repo: string, dir: string) => Promise<void>, config: Record<string, unknown> = {}): Promise<void> {
  const repo = makeRepo({ 'src/a.ts': 'a\n' });
  const dir = tmpDir('dic-handover-lead-');   // the lead's transcript, outside the daemon's home
  const d = await startTestDaemon({ verify: { resolveCommands: async () => [] }, requestHandover: true, config });
  try { await fn(d, repo, dir); } finally { await d.close(); rmrf(d.home); rmrf(repo); rmrf(dir); }
}

/** Every file under a folder whose bytes hold the text. */
function filesHolding(root: string, text: string): string[] {
  const hits: string[] = [];
  const walk = (p: string) => {
    for (const e of fs.readdirSync(p, { withFileTypes: true })) {
      const f = path.join(p, e.name);
      if (e.isDirectory()) walk(f);
      else if (fs.readFileSync(f).includes(text)) hits.push(path.relative(root, f));
    }
  };
  walk(root);
  return hits;
}

test('decision 219: the worker gets the user\'s request when it starts; the ledger, the daemon\'s files and the office and tab payloads never hold it', () => withDaemon(async (d, repo, dir) => {
  const sid = 'handover';
  const s = session(d, sid, repo, path.join(dir, `${sid}.jsonl`));
  await s.say(`${L2_PROMPT} Use the key ${TOKEN} for the test server.`);
  assert.deepEqual(await s.post(s.call('A')), {}, 'the request is readable: the call goes through');
  const context = await s.start('ag-a');
  assert.ok(context.includes('[do-it-all-claude-code] The user\'s request, as the user wrote it.'), context);
  assert.ok(context.includes(`----- the user's request -----\n${L2_PROMPT}`), context);
  assert.ok(context.includes('----- end of the user\'s request -----'));
  assert.ok(!context.includes(TOKEN), 'a secret in the request is masked');
  // a reviewer gets it too
  assert.deepEqual(await s.post(s.call('R', 'reviewer', 'sonnet', 'medium')), {});
  assert.ok((await s.start('ag-r', 'reviewer')).includes(MARKER));
  await d.router.drain();

  // nowhere the daemon keeps anything
  const tables = rows(d, "SELECT name FROM sqlite_master WHERE type = 'table'").map(r => String(r.name));
  for (const t of tables) assert.ok(!JSON.stringify(rows(d, `SELECT * FROM "${t}"`)).includes(MARKER), `table ${t}`);
  await d.close();
  assert.deepEqual(filesHolding(d.home, MARKER), [], 'no file of the daemon\'s home (ledger, logs, agent and scope files, notes) holds it');
}, {}));

test('decision 219: the office and tab payloads never carry the request', () => withDaemon(async (d, repo, dir) => {
  const sid = 'handover-views';
  const s = session(d, sid, repo, path.join(dir, `${sid}.jsonl`));
  await s.say(L2_PROMPT);
  assert.deepEqual(await s.post(s.call('A')), {});
  assert.ok((await s.start('ag-a')).includes(MARKER));
  await d.router.drain();
  const [req] = rows(d, 'SELECT id FROM requests');
  for (const route of [
    `/router/v1/office?session_id=${sid}`, `/router/v1/status?session_id=${sid}`, `/router/v1/metrics/work?session_id=${sid}`,
    `/router/v1/metrics/work/${String(req!.id)}`, `/router/v1/metrics/team?period=7d&session_id=${sid}`, '/router/v1/metrics/savings?period=7d',
    `/router/v1/office/settings?session_id=${sid}`,
  ]) {
    const r = await sealedApi(d.port, { path: route });
    assert.equal(r.status, 200, `${route}: ${r.text.slice(0, 200)}`);
    assert.ok(!r.text.includes(MARKER), route);
  }
}));

test('decision 219: the request is the opening prompt and the user\'s answers in it, without task notifications or an earlier request', () => withDaemon(async (d, repo, dir) => {
  const sid = 'handover-turns';
  const transcript = path.join(dir, `${sid}.jsonl`);
  const s = session(d, sid, repo, transcript);
  // an earlier request of the session, finished
  await s.say('Fix the typo in README.md');
  await s.post({ hook_event_name: 'Stop', stop_hook_active: false, last_assistant_message: 'Done.' });
  // this request: the lead asks, the user answers; a task notification comes in between
  await s.say(L2_PROMPT);
  fs.appendFileSync(transcript, assistant(`Which store? ${AWAITING_USER_MARKER}`) + '\n');
  await s.post({ hook_event_name: 'Stop', stop_hook_active: false, last_assistant_message: `Which store? ${AWAITING_USER_MARKER}` });
  await s.say('The file store, please.');
  const notification = '<task-notification>\n<task-id>ag-x</task-id>\n<status>completed</status>\n</task-notification>';
  fs.appendFileSync(transcript, user(notification) + '\n');
  await s.post({ hook_event_name: 'UserPromptSubmit', prompt: notification });
  assert.deepEqual(await s.post(s.call('A')), {});
  const context = await s.start('ag-a');
  assert.ok(context.includes(`${L2_PROMPT}\n\nThe user's answer to the lead's question:\nThe file store, please.`), context);
  assert.ok(!context.includes('Fix the typo'), 'the earlier request is not this one');
  assert.ok(!context.includes('task-notification'));
}));

test('decision 219: without a readable transcript the first call is refused with what to do; the call sent again goes through', () => withDaemon(async (d, repo, dir) => {
  const sid = 'handover-none';
  const s = session(d, sid, repo, path.join(dir, `${sid}.jsonl`), false);   // like claude -p --no-session-persistence
  await s.say(L2_PROMPT);
  const first = await s.post(s.call('A'));
  assert.equal(first.hookSpecificOutput?.permissionDecision, 'deny');
  assert.match(first.hookSpecificOutput?.permissionDecisionReason ?? '', /subtask A: the router could not read the user's request from this session's transcript, so it cannot give it to the worker\. Put the request in the prompt and send the call again\./);
  assert.equal(rows(d, 'SELECT id FROM subtasks').length, 0, 'a refused call leaves no subtask');
  assert.deepEqual(await s.post(s.call('A')), {}, 'sent again (now with the request in the prompt): through');
  assert.deepEqual(await s.post(s.call('B')), {}, 'the lead was told once for the request');
  assert.ok(!(await s.start('ag-a')).includes('the user\'s request'), 'nothing to hand over');
}));
